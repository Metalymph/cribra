/**
 * Pure Guard policy types and runtime validation.
 *
 * This module is deliberately free of browser APIs, storage, logging, network
 * access, and Cribra scanner calls. It carries opaque snapshot references and
 * sanitized counts only: never source text, matched values, transformed
 * documents, or raw diagnostics.
 */

import type { ScanResult, Severity } from "../cribra.js";

export const GUARD_SEVERITIES = [
  "info",
  "low",
  "medium",
  "high",
  "critical",
] as const satisfies readonly Severity[];

export type GuardSeverity = (typeof GUARD_SEVERITIES)[number];

export const MAX_GUARD_IDENTIFIER_LENGTH = 256;
export const MAX_GUARD_ORIGIN_LENGTH = 2_048;

/** The transformation offered as the primary user choice. */
export type TransformationPreference = "redact" | "template";

/** Redaction is the default; templating must be selected explicitly. */
export const DEFAULT_TRANSFORMATION_PREFERENCE: TransformationPreference =
  "redact";

/**
 * `unsupported` means the scanner could not establish complete coverage. It is
 * deliberately distinct both from a clean scan and from a complete scan with
 * findings or candidates. It never authorizes submission, transformation, or
 * explicit original approval.
 *
 * A site or channel outside the supported interception scope is a different
 * concern: absence of interception is not protection. That distinction belongs
 * to the future controller, not to this pure policy input.
 */
export type ScanCoverage = "complete" | "unsupported";

export interface GuardAdapterIdentity {
  readonly id: string;
  readonly version: string;
}

/**
 * Identity asserted by a future trusted controller.
 *
 * `origin` and `snapshotId` are assertions, not proof of authenticity. Browser
 * sender verification and exact source comparison belong to later milestones.
 */
export interface TransactionIdentity {
  /** Opaque submission identifier generated by the trusted controller. */
  readonly submissionId: string;
  /** Browser session or document identity. */
  readonly sessionId: string;
  readonly tabId: number;
  readonly frameId: number;
  /** Page-provided origin. Never treated as proof of authenticity. */
  readonly origin: string;
  readonly adapter: GuardAdapterIdentity;
  /** Opaque source snapshot identifier. Never treated as proof of authenticity. */
  readonly snapshotId: string;
}

/**
 * Sanitized scanner output. Counts are derived from the typed `ScanResult`;
 * source text, spans, matched values, and rule diagnostics are not retained.
 */
export interface ScanSummary {
  readonly snapshotId: string;
  readonly coverage: ScanCoverage;
  readonly findingCount: number;
  readonly candidateCount: number;
  readonly findingsBySeverity: Readonly<Record<Severity, number>>;
}

/**
 * Final verification asserted by the trusted controller immediately before it
 * consumes authorization. The pure state machine can only compare these fields
 * with the active transaction; it cannot verify the browser sender itself.
 *
 * `submissionId` identifies the transaction. `sessionId`, `tabId`, `frameId`,
 * and the adapter identity identify the browser context. `snapshotId` is the
 * exact source snapshot the controller intends to submit.
 *
 * An event whose submission, browser context, or adapter identity does not match
 * the active transaction is unrelated or stale and is rejected without
 * consuming authorization. A verified event for the active transaction whose
 * `snapshotId` differs from the authorized snapshot is a confirmed snapshot
 * mismatch and irreversibly invalidates the authorization.
 */
export interface FinalSnapshotVerification {
  readonly submissionId: string;
  readonly sessionId: string;
  readonly tabId: number;
  readonly frameId: number;
  readonly adapterId: string;
  readonly adapterVersion: string;
  readonly snapshotId: string;
}

/**
 * Explicit one-shot consent to send the original, bound to one submission and
 * one snapshot. There is intentionally no persistent always-allow variant.
 */
export interface OriginalApprovalConfirmation {
  readonly submissionId: string;
  readonly snapshotId: string;
  readonly confirmed: true;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function isNonEmptyBoundedString(
  value: unknown,
  maximum: number,
): value is string {
  return (
    typeof value === "string" && value.length > 0 && value.length <= maximum
  );
}

function isNonNegativeSafeInteger(value: unknown): value is number {
  return Number.isSafeInteger(value) && (value as number) >= 0;
}

/** Validates an opaque identifier used by Guard state. */
export function isValidGuardIdentifier(value: unknown): value is string {
  return isNonEmptyBoundedString(value, MAX_GUARD_IDENTIFIER_LENGTH);
}

/** Validates an explicit original-send confirmation shape. */
export function isValidOriginalApprovalConfirmation(
  value: unknown,
): value is OriginalApprovalConfirmation {
  if (!isRecord(value)) return false;
  return (
    value.confirmed === true &&
    isValidGuardIdentifier(value.submissionId) &&
    isValidGuardIdentifier(value.snapshotId)
  );
}

/** Validates the final snapshot verification shape. */
export function isValidFinalSnapshotVerification(
  value: unknown,
): value is FinalSnapshotVerification {
  if (!isRecord(value)) return false;
  return (
    isValidGuardIdentifier(value.submissionId) &&
    isValidGuardIdentifier(value.sessionId) &&
    isNonNegativeSafeInteger(value.tabId) &&
    isNonNegativeSafeInteger(value.frameId) &&
    isValidGuardIdentifier(value.adapterId) &&
    isValidGuardIdentifier(value.adapterVersion) &&
    isValidGuardIdentifier(value.snapshotId)
  );
}

/** Validates the trusted-controller transaction identity shape. */
export function isValidTransactionIdentity(
  value: unknown,
): value is TransactionIdentity {
  if (!isRecord(value)) return false;
  if (!isValidGuardIdentifier(value.submissionId)) return false;
  if (!isValidGuardIdentifier(value.sessionId)) return false;
  if (!isNonNegativeSafeInteger(value.tabId)) return false;
  if (!isNonNegativeSafeInteger(value.frameId)) return false;
  if (!isNonEmptyBoundedString(value.origin, MAX_GUARD_ORIGIN_LENGTH)) {
    return false;
  }
  if (!isRecord(value.adapter)) return false;
  if (!isValidGuardIdentifier(value.adapter.id)) return false;
  if (!isValidGuardIdentifier(value.adapter.version)) return false;
  return isValidGuardIdentifier(value.snapshotId);
}

/**
 * Validates and sanitizes an untrusted scan summary.
 *
 * Returns a fresh object containing only the known fields. Rejects negative or
 * non-integer counts and summaries whose severity totals disagree with
 * `findingCount`.
 */
export function parseScanSummary(value: unknown): ScanSummary | undefined {
  if (!isRecord(value)) return undefined;
  if (!isValidGuardIdentifier(value.snapshotId)) return undefined;
  if (value.coverage !== "complete" && value.coverage !== "unsupported") {
    return undefined;
  }
  if (!isNonNegativeSafeInteger(value.findingCount)) return undefined;
  if (!isNonNegativeSafeInteger(value.candidateCount)) return undefined;
  if (!isRecord(value.findingsBySeverity)) return undefined;

  const findingsBySeverity: Record<Severity, number> = {
    info: 0,
    low: 0,
    medium: 0,
    high: 0,
    critical: 0,
  };
  let total = 0;
  for (const severity of GUARD_SEVERITIES) {
    const count = value.findingsBySeverity[severity];
    if (!isNonNegativeSafeInteger(count)) return undefined;
    findingsBySeverity[severity] = count;
    total += count;
  }
  if (total !== value.findingCount) return undefined;

  return {
    snapshotId: value.snapshotId,
    coverage: value.coverage,
    findingCount: value.findingCount,
    candidateCount: value.candidateCount,
    findingsBySeverity,
  };
}

/**
 * Projects a typed `ScanResult` into the sanitized policy input.
 *
 * The scanner remains the sole detector. This function only counts typed
 * findings and candidates; it never copies spans, rule identifiers, or source.
 */
export function summarizeScan(
  snapshotId: string,
  coverage: ScanCoverage,
  result: ScanResult,
): ScanSummary {
  const findingsBySeverity: Record<Severity, number> = {
    info: 0,
    low: 0,
    medium: 0,
    high: 0,
    critical: 0,
  };
  // Derive counts from the typed arrays, not the redundant aggregate fields.
  for (const finding of result.findings) {
    findingsBySeverity[finding.severity] += 1;
  }
  return {
    snapshotId,
    coverage,
    findingCount: result.findings.length,
    candidateCount: result.candidates.length,
    findingsBySeverity,
  };
}
